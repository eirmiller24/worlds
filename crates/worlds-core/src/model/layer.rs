//! Layer definitions (`layers.json`) and per-level layer content
//! (`<layer>.json` files inside a level directory).

use std::borrow::Cow;
use std::collections::BTreeMap;

use schemars::{JsonSchema, Schema, SchemaGenerator};
use serde::{Deserialize, Deserializer, Serialize};

use super::common::{Color, Flip, VariantKeys, is_default, is_one, one, present, variant_schema};
use crate::id::Slug;

/// One entry of `layers.json`: the keys every layer has, plus its kind.
///
/// On disk the kind is the `kind` key and the kind's own keys sit next to
/// the common ones (`{ "slug", "name", "kind": "int_grid", "values", ... }`).
/// A key that belongs to another kind is a load error.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(try_from = "LayerDefRepr", into = "LayerDefRepr")]
pub struct LayerDef {
    pub slug: Slug,
    pub name: String,
    pub doc: Option<String>,
    /// Display opacity, 0 to 1. Default 1.
    pub opacity: f64,
    /// Cell size in pixels for this layer, if not the project's. Must divide
    /// or be a multiple of the project grid. An `auto` layer always uses its
    /// source's grid (setting a different one is a validation problem).
    pub grid_size: Option<u32>,
    pub kind: LayerKind,
}

/// What a layer holds, with the keys that only make sense for that kind.
#[derive(Debug, Clone, PartialEq)]
pub enum LayerKind {
    /// A grid of named values, stored as text rows (`<layer>.json`).
    IntGrid(IntGridDef),
    /// Hand-placed tiles, stored as a sparse list (`<layer>.json`).
    Tiles(TilesDef),
    /// Entity instances, stored in the level's `entities.json`.
    Entities,
    /// Tiles generated by the rules in `rules/<layer>.json`. Nothing is
    /// stored per level except the rule state in `level.json`.
    Auto(AutoDef),
}

/// `int_grid` layer keys.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct IntGridDef {
    /// The values cells can hold. `.` is reserved for empty.
    pub values: Vec<IntGridValue>,
    /// Named groups of values. Rule patterns can match a group slug.
    pub groups: Vec<IntGridGroup>,
    /// A grid computed by rules (`write` outputs) rather than painted. Its
    /// level files hold only hand-painted overrides ([`DerivedOverrides`]);
    /// rules, the export and the views read its effective values.
    pub derived: bool,
}

/// `tiles` layer keys.
#[derive(Debug, Clone, Default, PartialEq)]
pub struct TilesDef {
    /// Default tileset for the tile palette.
    pub tileset: Option<Slug>,
}

/// `auto` layer keys.
#[derive(Debug, Clone, PartialEq)]
pub struct AutoDef {
    /// The int_grid layer the rules read by default (`match.grid` default).
    pub source: Slug,
    /// Shifts stamp-mode rule output, in cells, 0 to 1 per axis (LDtk
    /// tilePivotX/Y). Default `[0, 0]`.
    pub tile_pivot: [f64; 2],
}

impl AutoDef {
    pub fn new(source: Slug) -> Self {
        AutoDef {
            source,
            tile_pivot: [0.0, 0.0],
        }
    }
}

impl LayerKind {
    /// The `kind` string: `int_grid`, `tiles`, `entities` or `auto`.
    pub fn name(&self) -> &'static str {
        match self {
            LayerKind::IntGrid(_) => "int_grid",
            LayerKind::Tiles(_) => "tiles",
            LayerKind::Entities => "entities",
            LayerKind::Auto(_) => "auto",
        }
    }
}

impl LayerDef {
    /// A layer definition of `kind` with every common option at its default.
    pub fn new(slug: Slug, name: impl Into<String>, kind: LayerKind) -> Self {
        LayerDef {
            slug,
            name: name.into(),
            doc: None,
            opacity: 1.0,
            grid_size: None,
            kind,
        }
    }

    pub fn int_grid(&self) -> Option<&IntGridDef> {
        match &self.kind {
            LayerKind::IntGrid(d) => Some(d),
            _ => None,
        }
    }

    pub fn int_grid_mut(&mut self) -> Option<&mut IntGridDef> {
        match &mut self.kind {
            LayerKind::IntGrid(d) => Some(d),
            _ => None,
        }
    }

    pub fn auto(&self) -> Option<&AutoDef> {
        match &self.kind {
            LayerKind::Auto(d) => Some(d),
            _ => None,
        }
    }

    pub fn auto_mut(&mut self) -> Option<&mut AutoDef> {
        match &mut self.kind {
            LayerKind::Auto(d) => Some(d),
            _ => None,
        }
    }

    pub fn tiles(&self) -> Option<&TilesDef> {
        match &self.kind {
            LayerKind::Tiles(d) => Some(d),
            _ => None,
        }
    }

    pub fn is_int_grid(&self) -> bool {
        matches!(self.kind, LayerKind::IntGrid(_))
    }

    /// An `int_grid` layer with `derived: true`.
    pub fn is_derived(&self) -> bool {
        self.int_grid().is_some_and(|d| d.derived)
    }

    pub fn is_tiles(&self) -> bool {
        matches!(self.kind, LayerKind::Tiles(_))
    }

    pub fn is_entities(&self) -> bool {
        matches!(self.kind, LayerKind::Entities)
    }

    pub fn is_auto(&self) -> bool {
        matches!(self.kind, LayerKind::Auto(_))
    }

    /// int_grid values; empty for other kinds.
    pub fn values(&self) -> &[IntGridValue] {
        self.int_grid().map_or(&[], |d| &d.values)
    }

    /// int_grid groups; empty for other kinds.
    pub fn groups(&self) -> &[IntGridGroup] {
        self.int_grid().map_or(&[], |d| &d.groups)
    }

    pub fn value(&self, slug: &str) -> Option<&IntGridValue> {
        self.values().iter().find(|v| v.slug == slug)
    }

    /// 1-based value index of a value slug (0 is empty), as stored in
    /// [`IntGridLayer`] cells.
    pub fn value_index(&self, slug: &str) -> Option<u16> {
        self.values()
            .iter()
            .position(|v| v.slug == slug)
            .map(|i| i as u16 + 1)
    }

    pub fn value_by_glyph(&self, glyph: char) -> Option<&IntGridValue> {
        self.values().iter().find(|v| v.glyph == glyph)
    }

    pub fn group(&self, slug: &str) -> Option<&IntGridGroup> {
        self.groups().iter().find(|g| g.slug == slug)
    }

    /// The legend an IntGrid file for this layer carries: `.` for empty
    /// plus every value's glyph.
    pub fn legend(&self) -> BTreeMap<char, Option<Slug>> {
        let mut legend = BTreeMap::from([(IntGridLayer::EMPTY, None)]);
        for v in self.values() {
            legend.insert(v.glyph, Some(v.slug.clone()));
        }
        legend
    }
}

/// Characters that can't be IntGrid value or group glyphs: `.` is the empty
/// glyph, `*` `+` `!` `@` `[` `]` `|` are (or will be) pattern syntax, and
/// `\` `"` need escaping inside JSON strings.
pub const RESERVED_GLYPHS: [char; 10] = ['.', '\\', '"', '*', '+', '!', '@', '[', ']', '|'];

/// Why `c` can't be a value or group glyph, if it can't.
pub fn glyph_problem(c: char) -> Option<String> {
    if !c.is_ascii_graphic() {
        Some(format!("glyph {c:?} must be printable ASCII (not a space)"))
    } else if c == IntGridLayer::EMPTY {
        Some("glyph '.' is reserved for empty".into())
    } else if RESERVED_GLYPHS.contains(&c) {
        Some(format!(
            "glyph {c:?} is reserved (none of . \\ \" * + ! @ [ ] | can be a value glyph)"
        ))
    } else {
        None
    }
}

fn glyph<'de, D: Deserializer<'de>>(d: D) -> Result<char, D::Error> {
    let c = char::deserialize(d)?;
    match glyph_problem(c) {
        Some(msg) => Err(serde::de::Error::custom(msg)),
        None => Ok(c),
    }
}

fn opt_glyph<'de, D: Deserializer<'de>>(d: D) -> Result<Option<char>, D::Error> {
    glyph(d).map(Some)
}

/// One value an IntGrid cell can hold.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct IntGridValue {
    pub slug: Slug,
    pub name: String,
    pub color: Color,
    /// The character that stands for this value in rows and patterns.
    /// Printable ASCII, not one of `. \ " * + ! @ [ ] |`.
    #[serde(deserialize_with = "glyph")]
    pub glyph: char,
    /// Optional group slug (from the layer's `groups`).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub group: Option<Slug>,
}

/// A named group of IntGrid values (LDtk "value groups").
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct IntGridGroup {
    pub slug: Slug,
    pub name: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub color: Option<Color>,
    /// Stands for "any value in this group" in rule patterns, without a
    /// legend entry. Same rules as value glyphs, unique among the layer's
    /// value and group glyphs. Never appears in grid rows.
    #[serde(
        default,
        deserialize_with = "opt_glyph",
        skip_serializing_if = "Option::is_none"
    )]
    pub glyph: Option<char>,
}

// ---- layers.json on disk: one flat object per layer ----

#[derive(Clone, Copy, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
enum KindTag {
    IntGrid,
    Tiles,
    Entities,
    Auto,
}

#[derive(Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
struct LayerDefRepr {
    slug: Slug,
    name: String,
    /// `int_grid`, `tiles`, `entities` or `auto`.
    kind: KindTag,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    doc: Option<String>,
    /// Display opacity, 0 to 1. Default 1.
    #[serde(default = "one", skip_serializing_if = "is_one")]
    opacity: f64,
    /// Cell size in pixels, if not the project's. Must divide or be a
    /// multiple of the project grid; an auto layer uses its source's.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    grid_size: Option<u32>,
    // Kind-specific keys are `Option`s so a key that is present at its
    // default value still counts as present (see `present`).
    /// int_grid: the values cells can hold.
    #[serde(
        default,
        deserialize_with = "present",
        skip_serializing_if = "Option::is_none"
    )]
    #[schemars(with = "Vec<IntGridValue>")]
    values: Option<Vec<IntGridValue>>,
    /// int_grid: named groups of values.
    #[serde(
        default,
        deserialize_with = "present",
        skip_serializing_if = "Option::is_none"
    )]
    #[schemars(with = "Vec<IntGridGroup>")]
    groups: Option<Vec<IntGridGroup>>,
    /// int_grid: computed by rules' `write` outputs; level files hold only
    /// overrides. Default false.
    #[serde(
        default,
        deserialize_with = "present",
        skip_serializing_if = "Option::is_none"
    )]
    #[schemars(with = "bool")]
    derived: Option<bool>,
    /// auto (required): the int_grid layer the rules read by default.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    source: Option<Slug>,
    /// auto: shifts stamp-mode output, in cells. Default `[0, 0]`.
    #[serde(
        default,
        deserialize_with = "present",
        skip_serializing_if = "Option::is_none"
    )]
    #[schemars(with = "[f64; 2]")]
    tile_pivot: Option<[f64; 2]>,
    /// tiles: default tileset for the palette.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    tileset: Option<Slug>,
}

const LAYER_VARIANTS: &[VariantKeys] = &[
    VariantKeys {
        name: "int_grid",
        keys: &["values", "groups", "derived"],
        required: &[],
    },
    VariantKeys {
        name: "tiles",
        keys: &["tileset"],
        required: &[],
    },
    VariantKeys {
        name: "entities",
        keys: &[],
        required: &[],
    },
    VariantKeys {
        name: "auto",
        keys: &["source", "tile_pivot"],
        required: &["source"],
    },
];

/// `Err` naming the first key in `set` that a `kind` layer can't have.
pub(crate) fn misplaced(kind: &str, what: &str, set: &[(&str, bool)]) -> Result<(), String> {
    match set.iter().find(|(_, on)| *on) {
        Some((key, _)) => Err(format!("{key:?} is not allowed on {kind} {what}s")),
        None => Ok(()),
    }
}

impl TryFrom<LayerDefRepr> for LayerDef {
    type Error = String;
    fn try_from(r: LayerDefRepr) -> Result<Self, String> {
        let name = match r.kind {
            KindTag::IntGrid => "int_grid",
            KindTag::Tiles => "tiles",
            KindTag::Entities => "entities",
            KindTag::Auto => "auto",
        };
        let int_grid_keys = [
            ("values", r.values.is_some()),
            ("groups", r.groups.is_some()),
            ("derived", r.derived.is_some()),
        ];
        let auto_keys = [
            ("source", r.source.is_some()),
            ("tile_pivot", r.tile_pivot.is_some()),
        ];
        let tiles_keys = [("tileset", r.tileset.is_some())];
        let kind = match r.kind {
            KindTag::IntGrid => {
                misplaced(name, "layer", &auto_keys)?;
                misplaced(name, "layer", &tiles_keys)?;
                LayerKind::IntGrid(IntGridDef {
                    values: r.values.unwrap_or_default(),
                    groups: r.groups.unwrap_or_default(),
                    derived: r.derived.unwrap_or_default(),
                })
            }
            KindTag::Tiles => {
                misplaced(name, "layer", &int_grid_keys)?;
                misplaced(name, "layer", &auto_keys)?;
                LayerKind::Tiles(TilesDef { tileset: r.tileset })
            }
            KindTag::Entities => {
                misplaced(name, "layer", &int_grid_keys)?;
                misplaced(name, "layer", &auto_keys)?;
                misplaced(name, "layer", &tiles_keys)?;
                LayerKind::Entities
            }
            KindTag::Auto => {
                misplaced(name, "layer", &int_grid_keys)?;
                misplaced(name, "layer", &tiles_keys)?;
                LayerKind::Auto(AutoDef {
                    source: r
                        .source
                        .ok_or("auto layers need a \"source\" int_grid layer")?,
                    tile_pivot: r.tile_pivot.unwrap_or_default(),
                })
            }
        };
        Ok(LayerDef {
            slug: r.slug,
            name: r.name,
            doc: r.doc,
            opacity: r.opacity,
            grid_size: r.grid_size,
            kind,
        })
    }
}

impl From<LayerDef> for LayerDefRepr {
    fn from(l: LayerDef) -> Self {
        let mut r = LayerDefRepr {
            slug: l.slug,
            name: l.name,
            kind: KindTag::Entities,
            doc: l.doc,
            opacity: l.opacity,
            grid_size: l.grid_size,
            values: None,
            groups: None,
            derived: None,
            source: None,
            tile_pivot: None,
            tileset: None,
        };
        // Keys at their default are left out.
        match l.kind {
            LayerKind::IntGrid(d) => {
                r.kind = KindTag::IntGrid;
                r.values = (!d.values.is_empty()).then_some(d.values);
                r.groups = (!d.groups.is_empty()).then_some(d.groups);
                r.derived = d.derived.then_some(true);
            }
            LayerKind::Tiles(d) => {
                r.kind = KindTag::Tiles;
                r.tileset = d.tileset;
            }
            LayerKind::Entities => {}
            LayerKind::Auto(d) => {
                r.kind = KindTag::Auto;
                r.source = Some(d.source);
                r.tile_pivot = (d.tile_pivot != [0.0, 0.0]).then_some(d.tile_pivot);
            }
        }
        r
    }
}

impl JsonSchema for LayerDef {
    fn schema_name() -> Cow<'static, str> {
        "LayerDef".into()
    }
    fn json_schema(generator: &mut SchemaGenerator) -> Schema {
        variant_schema(
            LayerDefRepr::json_schema(generator),
            Some("kind"),
            LAYER_VARIANTS,
            "A layer definition. Keys after `opacity`/`grid_size` depend on `kind`.",
        )
    }
}

/// Per-level rule state for one `auto` layer, stored in `level.json` under
/// `layers`. A layer without an entry uses the defaults.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct LayerState {
    /// Extra seed for this layer's rules in this level. Default 0. The rule
    /// hash already differs per project, level, layer and rule; change this
    /// only to re-roll the layer's random choices in this level.
    #[serde(default, skip_serializing_if = "is_default")]
    pub seed: i64,
    /// `optional` rule groups switched on in this level.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub optional_groups: Vec<Slug>,
    /// Tileset substitutions in this level: every rule output drawing from
    /// the key tileset draws from the value tileset instead, same
    /// `[col, row]` (LDtk overrideTilesetUid).
    #[serde(default, skip_serializing_if = "BTreeMap::is_empty")]
    pub tilesets: BTreeMap<Slug, Slug>,
}

/// An IntGrid layer's content in one level (the `<layer>.json` file, parsed).
///
/// Cells are a dense row-major array of value indices into the layer
/// definition's `values`: 0 is empty, `i + 1` is `values[i]`. The text rows
/// only exist in the file; see `worlds_core::format`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct IntGridLayer {
    /// Layer slug.
    pub layer: Slug,
    size: [u32; 2],
    cells: Vec<u16>,
}

impl IntGridLayer {
    /// The empty glyph.
    pub const EMPTY: char = '.';

    /// An all-empty grid of `size` cells (of the layer's grid) for `def`.
    pub fn new_empty(def: &LayerDef, size: [u32; 2]) -> Self {
        IntGridLayer {
            layer: def.slug.clone(),
            size,
            cells: vec![0; size[0] as usize * size[1] as usize],
        }
    }

    /// A grid from row-major value indices. Panics unless `cells` has
    /// `size[0] * size[1]` entries.
    pub fn from_cells(layer: Slug, size: [u32; 2], cells: Vec<u16>) -> Self {
        assert_eq!(
            cells.len(),
            size[0] as usize * size[1] as usize,
            "cell count"
        );
        IntGridLayer { layer, size, cells }
    }

    /// A grid from text rows, each glyph read with `def`'s value glyphs
    /// (`.` is empty). Errors name the row: `(index, message)`.
    pub fn from_rows<S: AsRef<str>>(def: &LayerDef, rows: &[S]) -> Result<Self, (usize, String)> {
        let w = rows.first().map_or(0, |r| r.as_ref().chars().count());
        let mut cells = Vec::with_capacity(w * rows.len());
        for (y, row) in rows.iter().enumerate() {
            let row = row.as_ref();
            let n = row.chars().count();
            if n != w {
                return Err((y, format!("row has {n} glyphs, the first row has {w}")));
            }
            for c in row.chars() {
                cells.push(match c {
                    Self::EMPTY => 0,
                    DerivedOverrides::SUPPRESS => {
                        return Err((
                            y,
                            format!(
                                "'!' (suppress) only appears in a derived layer's file; layer \
                                 {:?} isn't derived",
                                def.slug.as_str()
                            ),
                        ));
                    }
                    c => match def.value_by_glyph(c) {
                        Some(v) => def.value_index(v.slug.as_str()).expect("own value"),
                        None => {
                            return Err((
                                y,
                                format!(
                                    "glyph {c:?} is not a value of layer {:?}",
                                    def.slug.as_str()
                                ),
                            ));
                        }
                    },
                });
            }
        }
        Ok(IntGridLayer {
            layer: def.slug.clone(),
            size: [w as u32, rows.len() as u32],
            cells,
        })
    }

    /// The grid as text rows with `def`'s glyphs. Errs on a value index the
    /// definition doesn't have.
    pub fn to_rows(&self, def: &LayerDef) -> Result<Vec<String>, String> {
        let values = def.values();
        let w = self.size[0] as usize;
        let mut rows = Vec::with_capacity(self.size[1] as usize);
        for (y, row) in self.cells.chunks(w.max(1)).enumerate() {
            let mut s = String::with_capacity(w);
            for (x, &i) in row.iter().enumerate() {
                s.push(match i {
                    0 => Self::EMPTY,
                    i => match values.get(i as usize - 1) {
                        Some(v) => v.glyph,
                        None => {
                            return Err(format!(
                                "cell [{x}, {y}] holds value #{i}, but layer {:?} has {} values",
                                def.slug.as_str(),
                                values.len()
                            ));
                        }
                    },
                });
            }
            rows.push(s);
        }
        if w == 0 {
            rows = vec![String::new(); self.size[1] as usize];
        }
        Ok(rows)
    }

    /// `[width, height]` in cells of the layer's grid.
    pub fn size(&self) -> [u32; 2] {
        self.size
    }

    /// Row-major value indices.
    pub fn cells(&self) -> &[u16] {
        &self.cells
    }

    /// True when every cell is empty.
    pub fn is_empty(&self) -> bool {
        self.cells.iter().all(|&c| c == 0)
    }

    /// The value index at a cell (0 = empty); `None` out of range.
    pub fn index_at(&self, x: u32, y: u32) -> Option<u16> {
        (x < self.size[0] && y < self.size[1]).then(|| self.cells[(y * self.size[0] + x) as usize])
    }

    /// The value slug at a cell; `None` for empty, out of range, or an
    /// index `def` doesn't have.
    pub fn value_at<'d>(&self, def: &'d LayerDef, x: u32, y: u32) -> Option<&'d Slug> {
        let i = self.index_at(x, y)?;
        def.values()
            .get((i as usize).checked_sub(1)?)
            .map(|v| &v.slug)
    }

    /// Set a cell to a value index (0 = empty). False when out of range.
    pub fn set_index(&mut self, x: u32, y: u32, index: u16) -> bool {
        if x >= self.size[0] || y >= self.size[1] {
            return false;
        }
        self.cells[(y * self.size[0] + x) as usize] = index;
        true
    }

    /// Set a cell to a value of `def` by slug, or empty with `None`. False
    /// when out of range or `def` has no such value.
    pub fn set_value(&mut self, def: &LayerDef, x: u32, y: u32, value: Option<&str>) -> bool {
        let index = match value {
            None => 0,
            Some(s) => match def.value_index(s) {
                Some(i) => i,
                None => return false,
            },
        };
        self.set_index(x, y, index)
    }
}

/// One cell of a derived layer's override plane.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum Override {
    /// No override: the rules decide (`.` in the file).
    None,
    /// This value, whatever the rules say: a 1-based index into the
    /// layer's `values`, as in [`IntGridLayer`].
    Value(u16),
    /// Empty, whatever the rules say (`!` in the file).
    Suppress,
}

/// A derived `int_grid` layer's hand-painted overrides in one level (its
/// `<layer>.json`, which says `"overrides": true`).
///
/// Never an [`IntGridLayer`]: code that reads value grids never sees an
/// override plane. What rules, the export and the views read is the
/// **effective** grid ([`DerivedOverrides::effective`]): the override where
/// there is one, else the value the rules computed.
///
/// `values` is row-major, 0 = no value override, `i + 1` = `values[i]` of
/// the layer; `suppressed` is a bitset of the cells overridden to empty. A
/// cell never has both.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DerivedOverrides {
    /// Layer slug.
    pub layer: Slug,
    size: [u32; 2],
    values: Vec<u16>,
    suppressed: Vec<u64>,
}

impl DerivedOverrides {
    /// The glyph of a suppressed cell in files and the text view.
    pub const SUPPRESS: char = '!';
    /// Stored state code of a suppressed cell inside commands only (never
    /// a value index: a layer has fewer than `u16::MAX` values).
    pub(crate) const SUPPRESS_CODE: u16 = u16::MAX;

    /// No overrides on a `size` grid of `def`.
    pub fn new_empty(def: &LayerDef, size: [u32; 2]) -> Self {
        Self::empty(def.slug.clone(), size)
    }

    fn empty(layer: Slug, size: [u32; 2]) -> Self {
        let n = size[0] as usize * size[1] as usize;
        DerivedOverrides {
            layer,
            size,
            values: vec![0; n],
            suppressed: vec![0; n.div_ceil(64)],
        }
    }

    /// From one state per cell, row-major. Panics unless `cells` has
    /// `size[0] * size[1]` entries.
    pub fn from_cells(layer: Slug, size: [u32; 2], cells: &[Override]) -> Self {
        let mut o = Self::empty(layer, size);
        assert_eq!(cells.len(), o.values.len(), "cell count");
        for (i, c) in cells.iter().enumerate() {
            o.set_at(i, *c);
        }
        o
    }

    /// `[width, height]` in cells of the layer's grid.
    pub fn size(&self) -> [u32; 2] {
        self.size
    }

    /// Row-major value overrides: 0 = none, `i + 1` = `values[i]`.
    pub fn values(&self) -> &[u16] {
        &self.values
    }

    fn index(&self, x: u32, y: u32) -> Option<usize> {
        (x < self.size[0] && y < self.size[1]).then(|| (y * self.size[0] + x) as usize)
    }

    fn suppressed_at(&self, i: usize) -> bool {
        self.suppressed[i / 64] & (1 << (i % 64)) != 0
    }

    fn state_at(&self, i: usize) -> Override {
        if self.suppressed_at(i) {
            Override::Suppress
        } else if self.values[i] != 0 {
            Override::Value(self.values[i])
        } else {
            Override::None
        }
    }

    fn set_at(&mut self, i: usize, o: Override) {
        let (word, bit) = (i / 64, 1u64 << (i % 64));
        match o {
            Override::None => {
                self.values[i] = 0;
                self.suppressed[word] &= !bit;
            }
            Override::Value(v) => {
                self.values[i] = v;
                self.suppressed[word] &= !bit;
            }
            Override::Suppress => {
                self.values[i] = 0;
                self.suppressed[word] |= bit;
            }
        }
    }

    /// The state of a cell; `None` out of range.
    pub fn get(&self, x: u32, y: u32) -> Option<Override> {
        self.index(x, y).map(|i| self.state_at(i))
    }

    /// Whether a cell is overridden to empty.
    pub fn is_suppressed(&self, x: u32, y: u32) -> bool {
        self.index(x, y).is_some_and(|i| self.suppressed_at(i))
    }

    /// Set a cell's state. False when out of range.
    pub fn set(&mut self, x: u32, y: u32, o: Override) -> bool {
        match self.index(x, y) {
            Some(i) => {
                self.set_at(i, o);
                true
            }
            None => false,
        }
    }

    /// Every cell's state, row-major.
    pub fn cells(&self) -> impl Iterator<Item = Override> + '_ {
        (0..self.values.len()).map(|i| self.state_at(i))
    }

    /// True when no cell has an override.
    pub fn is_empty(&self) -> bool {
        self.values.iter().all(|&v| v == 0) && self.suppressed.iter().all(|&w| w == 0)
    }

    /// `(value overrides, suppressed cells)`.
    pub fn counts(&self) -> (usize, usize) {
        let set = self.values.iter().filter(|&&v| v != 0).count();
        let sup = self
            .suppressed
            .iter()
            .map(|w| w.count_ones() as usize)
            .sum();
        (set, sup)
    }

    /// The command-internal state code of a cell: 0 none, `i + 1` a value,
    /// [`Self::SUPPRESS_CODE`] suppressed. Panics out of range.
    pub(crate) fn code_at(&self, x: u32, y: u32) -> u16 {
        match self.get(x, y).expect("cell inside the grid") {
            Override::None => 0,
            Override::Value(v) => v,
            Override::Suppress => Self::SUPPRESS_CODE,
        }
    }

    /// Set a cell from a state code (see [`Self::code_at`]).
    pub(crate) fn set_code(&mut self, x: u32, y: u32, code: u16) -> bool {
        self.set(x, y, Self::override_of(code))
    }

    pub(crate) fn override_of(code: u16) -> Override {
        match code {
            0 => Override::None,
            Self::SUPPRESS_CODE => Override::Suppress,
            v => Override::Value(v),
        }
    }

    /// The effective grid: the override where there is one, else
    /// `computed`'s value (empty where `computed` is `None` or smaller).
    pub fn effective(&self, computed: Option<&IntGridLayer>) -> IntGridLayer {
        Self::effective_of(Some(self), self.layer.clone(), self.size, computed)
    }

    /// The effective grid of derived layer `layer` on a `size` grid: the
    /// override in `overrides` where there is one (a suppressed cell is
    /// empty), else `computed`'s value (empty where `computed` is `None` or
    /// smaller). The one place this is worked out
    /// ([`crate::Project::derived_effective`] sizes it for a level).
    pub fn effective_of(
        overrides: Option<&Self>,
        layer: Slug,
        size: [u32; 2],
        computed: Option<&IntGridLayer>,
    ) -> IntGridLayer {
        let [w, h] = size;
        let mut cells = Vec::with_capacity(w as usize * h as usize);
        for y in 0..h {
            for x in 0..w {
                cells.push(match overrides.and_then(|o| o.get(x, y)) {
                    Some(Override::Value(v)) => v,
                    Some(Override::Suppress) => 0,
                    _ => computed.and_then(|c| c.index_at(x, y)).unwrap_or(0),
                });
            }
        }
        IntGridLayer::from_cells(layer, size, cells)
    }

    /// From text rows: `.` no override, a value glyph of `def`, `!`
    /// suppressed. Errors name the row: `(index, message)`.
    pub fn from_rows<S: AsRef<str>>(def: &LayerDef, rows: &[S]) -> Result<Self, (usize, String)> {
        let w = rows.first().map_or(0, |r| r.as_ref().chars().count());
        let mut cells = Vec::with_capacity(w * rows.len());
        for (y, row) in rows.iter().enumerate() {
            let row = row.as_ref();
            let n = row.chars().count();
            if n != w {
                return Err((y, format!("row has {n} glyphs, the first row has {w}")));
            }
            for c in row.chars() {
                cells.push(match c {
                    IntGridLayer::EMPTY => Override::None,
                    Self::SUPPRESS => Override::Suppress,
                    c => match def.value_by_glyph(c) {
                        Some(v) => Override::Value(def.value_index(v.slug.as_str()).expect("own")),
                        None => {
                            return Err((
                                y,
                                format!(
                                    "glyph {c:?} is not a value of layer {:?} (a derived \
                                     layer's file holds . for no override, ! to suppress, or \
                                     a value glyph)",
                                    def.slug.as_str()
                                ),
                            ));
                        }
                    },
                });
            }
        }
        Ok(Self::from_cells(
            def.slug.clone(),
            [w as u32, rows.len() as u32],
            &cells,
        ))
    }

    /// The overrides as text rows: `.` none, `!` suppressed, else the
    /// value's glyph. Errs on a value index `def` doesn't have.
    pub fn to_rows(&self, def: &LayerDef) -> Result<Vec<String>, String> {
        let values = def.values();
        let w = self.size[0] as usize;
        let mut rows = Vec::with_capacity(self.size[1] as usize);
        for y in 0..self.size[1] as usize {
            let mut s = String::with_capacity(w);
            for x in 0..w {
                s.push(match self.state_at(y * w + x) {
                    Override::None => IntGridLayer::EMPTY,
                    Override::Suppress => Self::SUPPRESS,
                    Override::Value(i) => match values.get(i as usize - 1) {
                        Some(v) => v.glyph,
                        None => {
                            return Err(format!(
                                "cell [{x}, {y}] holds value #{i}, but layer {:?} has {} values",
                                def.slug.as_str(),
                                values.len()
                            ));
                        }
                    },
                });
            }
            rows.push(s);
        }
        Ok(rows)
    }
}

/// A Tiles layer's content in one level: `<layer>.json`.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct TilesLayer {
    /// Layer slug.
    pub layer: Slug,
    /// Placements, kept sorted by row then column. Several placements in one
    /// cell stack in list order.
    pub tiles: Vec<TilePlacement>,
}

impl TilesLayer {
    /// Stable sort by row then column (stacking order within a cell is kept).
    pub fn sort(&mut self) {
        self.tiles.sort_by_key(|t| (t.cell[1], t.cell[0]));
    }
}

/// One placed tile.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize, JsonSchema)]
#[serde(deny_unknown_fields)]
pub struct TilePlacement {
    /// `[x, y]` cell of the layer's grid. The tile's top-left corner sits on
    /// the cell's top-left corner.
    pub cell: [u32; 2],
    pub tileset: Slug,
    /// `[column, row]` in the tileset atlas.
    pub tile: [u32; 2],
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub flip: Option<Flip>,
    /// Opacity, 0 to 1. Default 1.
    #[serde(default = "one", skip_serializing_if = "is_one")]
    pub alpha: f64,
}
